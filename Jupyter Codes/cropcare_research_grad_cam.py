#Generate Heatmap
# Feature extractor up to top_conv
feature_extractor = tf.keras.Model(
    efficientnet.input,
    efficientnet.get_layer("top_conv").output
)

input_tensor = tf.convert_to_tensor(input_image)

with tf.GradientTape() as tape:

    feature_maps = feature_extractor(input_tensor)

    tape.watch(feature_maps)

    predictions = classifier_model(feature_maps)

    predicted_class = tf.argmax(predictions[0])

    class_channel = predictions[:, predicted_class]

grads = tape.gradient(class_channel, feature_maps)

pooled_grads = tf.reduce_mean(grads, axis=(0, 1, 2))

feature_maps = feature_maps[0]

heatmap = tf.reduce_sum(
    feature_maps * pooled_grads,
    axis=-1
)

heatmap = tf.maximum(heatmap, 0)

heatmap /= (tf.reduce_max(heatmap) + 1e-8)

heatmap = heatmap.numpy()

print("Heatmap generated successfully")

