# ─────────────────────────────────────────────────────────────────
#  generate_yield_dataset.py
#
#  DATASET NEEDED:
#  Name : Crop Recommendation Dataset
#  URL  : https://www.kaggle.com/datasets/atharvaingle/crop-recommendation-dataset
#  File : Crop_recommendation.csv
#
#  WHY THIS DATASET:
#  It has N, P, K, temperature, humidity, ph, rainfall, label — exactly
#  what CropCare collects from SHC + NASA POWER. No other public dataset
#  combines all these features for Indian crops.
#
#  WHAT THIS SCRIPT DOES:
#  Adds per-crop yield_qtl_acre values using ICAR (Indian Council of
#  Agricultural Research) benchmark ranges with realistic Gaussian noise.
#  Yield is modulated by soil and climate quality scores so the model
#  learns meaningful feature-to-yield relationships.
#
#  OUTPUT: crop_yield_dataset.csv  (used by train_yield_model.py)
#
#  Run: python generate_yield_dataset.py
# ─────────────────────────────────────────────────────────────────

import pandas as pd
import numpy as np

np.random.seed(42)

# ── ICAR yield benchmarks per crop (quintals/acre) ────────────────
# Sources: ICAR crop production guides, Krishi Vigyan Kendra data,
#          Directorate of Economics and Statistics, Govt. of India
CROP_YIELD_BENCHMARKS = {
    # crop:  (mean_qtl_acre, std_dev)
    "rice":        (18.0, 3.5),
    "maize":       (22.0, 4.0),
    "chickpea":    (8.0,  1.5),
    "kidneybeans": (7.0,  1.2),
    "pigeonpeas":  (6.5,  1.2),
    "mothbeans":   (5.0,  1.0),
    "mungbean":    (5.5,  1.0),
    "blackgram":   (5.0,  1.0),
    "lentil":      (7.0,  1.3),
    "pomegranate": (50.0, 8.0),
    "banana":      (200.0,30.0),
    "mango":       (40.0, 7.0),
    "grapes":      (80.0, 12.0),
    "watermelon":  (120.0,20.0),
    "muskmelon":   (80.0, 15.0),
    "apple":       (60.0, 10.0),
    "orange":      (55.0, 9.0),
    "papaya":      (120.0,20.0),
    "coconut":     (35.0, 6.0),   # in hundreds of nuts/acre → converted to qtl
    "cotton":      (8.0,  1.5),   # seed cotton
    "jute":        (12.0, 2.0),
    "coffee":      (4.0,  0.8),
}

# ── Soil quality score (0–1) based on NPK and pH ─────────────────
def soil_quality_score(N, P, K, ph):
    """
    Higher score = better soil conditions = higher yield.
    Based on ICAR optimal ranges.
    """
    # Optimal pH range 6.0–7.5
    ph_score = 1.0 if 6.0 <= ph <= 7.5 else max(0.5, 1 - abs(ph - 6.75) * 0.15)
    # N score (optimal ~80–120 for most crops)
    n_score = min(1.0, N / 90.0) if N < 90 else max(0.8, 1 - (N - 120) * 0.005)
    # P score (optimal ~40–60)
    p_score = min(1.0, P / 45.0) if P < 45 else max(0.8, 1 - (P - 60) * 0.005)
    # K score (optimal ~40–60)
    k_score = min(1.0, K / 45.0) if K < 45 else max(0.8, 1 - (K - 60) * 0.005)
    return (ph_score * 0.3 + n_score * 0.3 + p_score * 0.2 + k_score * 0.2)

# ── Climate quality score (0–1) ───────────────────────────────────
def climate_quality_score(temperature, humidity, rainfall):
    """Mild boost/penalty based on climate favourability."""
    # Optimal temp 20–30°C
    t_score = 1.0 if 20 <= temperature <= 30 else max(0.6, 1 - abs(temperature - 25) * 0.03)
    # Optimal humidity 60–85%
    h_score = 1.0 if 60 <= humidity <= 85 else max(0.6, 1 - abs(humidity - 72) * 0.01)
    # Rainfall > 80mm generally good
    r_score = min(1.0, rainfall / 100.0)
    return (t_score * 0.4 + h_score * 0.3 + r_score * 0.3)

# ── Main ──────────────────────────────────────────────────────────
def generate(input_csv="Crop_recommendation-dataset.csv", output_csv="crop_yield_dataset.csv"):
    df = pd.read_csv(input_csv)
    df.columns = [c.strip().lower() for c in df.columns]

    # Rename 'label' → 'crop' for clarity
    df = df.rename(columns={"label": "crop"})
    df["crop"] = df["crop"].str.strip().str.lower()

    print(f"Loaded {len(df)} rows. Crops: {sorted(df['crop'].unique())}")

    unknown = [c for c in df["crop"].unique() if c not in CROP_YIELD_BENCHMARKS]
    if unknown:
        print(f"WARNING: No benchmark for crops: {unknown}. They will be dropped.")
        df = df[df["crop"].isin(CROP_YIELD_BENCHMARKS.keys())]

    yields = []
    for _, row in df.iterrows():
        crop = row["crop"]
        mean_yield, std = CROP_YIELD_BENCHMARKS[crop]

        # Modulate by soil and climate quality
        sq = soil_quality_score(row["n"], row["p"], row["k"], row["ph"])
        cq = climate_quality_score(row["temperature"], row["humidity"], row["rainfall"])
        quality_factor = 0.5 + (sq * 0.6 + cq * 0.4) * 0.5  # range ~0.5–1.0

        # Final yield = benchmark × quality factor + noise
        y = np.random.normal(mean_yield * quality_factor, std * 0.5)
        y = max(y, mean_yield * 0.3)  # floor at 30% of mean
        yields.append(round(y, 2))

    df["yield_qtl_acre"] = yields

    # Reorder columns
    df = df[["crop", "n", "p", "k", "temperature", "humidity", "ph", "rainfall", "yield_qtl_acre"]]

    df.to_csv(output_csv, index=False)
    print(f"\nSaved {len(df)} rows → {output_csv}")
    print("\nPer-crop yield summary (qtl/acre):")
    print(df.groupby("crop")["yield_qtl_acre"].agg(["mean", "std", "min", "max"]).round(2).to_string())

if __name__ == "__main__":
    generate()

# ─────────────────────────────────────────────────────────────────
#  train_yield_model.py
#
#  Input : crop_yield_dataset.csv  (from generate_yield_dataset.py)
#  Output: yield_model.pkl | yield_scaler.pkl | yield_label_encoder.pkl
#
#  Model : XGBoost Regressor
#  Target: yield_qtl_acre (quintals per acre)
#
#  Features (matches exactly what CropCare collects):
#    N, P, K, temperature, humidity, ph, rainfall, crop (encoded)
#
#  Run: python train_yield_model.py
# ─────────────────────────────────────────────────────────────────

import pandas as pd
import numpy as np
from sklearn.preprocessing import LabelEncoder, StandardScaler
from sklearn.model_selection import train_test_split, cross_val_score
from sklearn.metrics import mean_absolute_error, r2_score, mean_squared_error
from xgboost import XGBRegressor
import joblib
import warnings
warnings.filterwarnings("ignore")

# 1. Load
df = pd.read_csv("crop_yield_dataset.csv")
print(f"Loaded: {len(df)} rows | Crops: {df['crop'].nunique()}")
print(f"Columns: {list(df.columns)}")

# 2. Encode crop
le = LabelEncoder()
df["crop_encoded"] = le.fit_transform(df["crop"])
print(f"\nCrops encoded ({len(le.classes_)}): {list(le.classes_)}")

# 3. Features and target
FEATURES = ["n", "p", "k", "temperature", "humidity", "ph", "rainfall", "crop_encoded"]
X = df[FEATURES].values.astype(np.float64)
y = df["yield_qtl_acre"].values.astype(np.float64)

# Log transform NPK — matches crop recommendation model preprocessing
X[:, 0:3] = np.log1p(X[:, 0:3])

# 4. Scale
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# 5. Train/Test split
X_train, X_test, y_train, y_test = train_test_split(
    X_scaled, y, test_size=0.2, random_state=42
)
print(f"\nTrain: {len(X_train)} | Test: {len(X_test)}")

# 6. Train XGBoost
model = XGBRegressor(
    n_estimators=300,
    max_depth=6,
    learning_rate=0.05,
    subsample=0.8,
    colsample_bytree=0.8,
    min_child_weight=3,
    random_state=42,
    n_jobs=-1
)
model.fit(X_train, y_train, eval_set=[(X_test, y_test)], verbose=False)

# 7. Evaluate
preds = model.predict(X_test)
mae  = mean_absolute_error(y_test, preds)
rmse = np.sqrt(mean_squared_error(y_test, preds))
r2   = r2_score(y_test, preds)

print(f"\nTest Set Metrics")
print(f"MAE  : {mae:.3f} qtl/acre")
print(f"RMSE : {rmse:.3f} qtl/acre")
print(f"R2   : {r2:.4f}")

# 8. Cross-validation
cv_scores = cross_val_score(
    XGBRegressor(n_estimators=200, max_depth=6, learning_rate=0.05, random_state=42),
    X_scaled, y, cv=5, scoring="r2"
)
print(f"\n5-Fold CV R2: {[round(s, 4) for s in cv_scores]}")
print(f"Mean: {cv_scores.mean():.4f} +/- {cv_scores.std():.4f}")

# 9. Feature importance
importance = dict(zip(FEATURES, model.feature_importances_))
print(f"\nFeature Importance:")
for feat, imp in sorted(importance.items(), key=lambda x: -x[1]):
    print(f"  {feat:15s}: {imp:.4f}")

# 10. Save
joblib.dump(model,  "yield_model.pkl")
joblib.dump(scaler, "yield_scaler.pkl")
joblib.dump(le,     "yield_label_encoder.pkl")

print(f"\nSaved: yield_model.pkl | yield_scaler.pkl | yield_label_encoder.pkl")
print(f"\nSupported crops for /predict-yield:")
print(list(le.classes_))

