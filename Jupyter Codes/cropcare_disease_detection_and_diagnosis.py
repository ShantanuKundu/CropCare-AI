#Unzipping the crop files
import zipfile
with zipfile.ZipFile("PlantVillage-6-Crops-zip.zip","r") as zip_ref:
  zip_ref.extractall()

import os
data_dir = "/content/PlantVillage"
print(os.listdir(data_dir))

"""# <h4>Phase 1: Data Pipeline</h4>"""

#Loading the Dataset
import tensorflow as tf

data_dir = "/content/PlantVillage"

BATCH_SIZE = 16
IMG_SIZE = (128, 128)
SEED = 123

train_ds = tf.keras.preprocessing.image_dataset_from_directory(
    data_dir,
    validation_split=0.2,
    subset="training",
    seed=SEED,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE
)

val_ds = tf.keras.preprocessing.image_dataset_from_directory(
    data_dir,
    validation_split=0.2,
    subset="validation",
    seed=SEED,
    image_size=IMG_SIZE,
    batch_size=BATCH_SIZE
)

class_names = train_ds.class_names
num_classes = len(class_names)

print("Classes:", class_names)
print("Total Classes:", num_classes)

#Performance Optimization
AUTOTUNE = tf.data.AUTOTUNE

train_ds = train_ds.shuffle(1000).prefetch(buffer_size=AUTOTUNE)
val_ds = val_ds.prefetch(buffer_size=AUTOTUNE)

#Data Augmentation
from tensorflow.keras import layers

data_augmentation = tf.keras.Sequential([
    layers.RandomFlip("horizontal"),
    layers.RandomRotation(0.1),
    layers.RandomZoom(0.1),
])

#MobileNet Preprocessing
from tensorflow.keras.applications.efficientnet import preprocess_input

"""# <h4>Phase 2: Model Architecture (Transfer Learning)</h4>"""

#Loading the Base Model
from tensorflow.keras.applications import EfficientNetB0, MobileNetV2

# base_model = MobileNetV2(
#     input_shape=(224, 224, 3),
#     include_top=False,
#     weights="imagenet"
# )

base_model = EfficientNetB0(
    input_shape=(128, 128, 3),
    include_top=False,
    weights="imagenet"
)

base_model.trainable = False  # Freeze pretrained layers

#Building the Full Model
from tensorflow.keras import layers, models

model = models.Sequential([
    data_augmentation,                    # Step 3 from Phase 1
    layers.Lambda(preprocess_input),      # Step 4 from Phase 1
    base_model,
    layers.GlobalAveragePooling2D(),
    layers.Dense(128, activation="relu"),
    layers.Dropout(0.3),
    layers.Dense(num_classes, activation="softmax")
])

model.summary()

"""# <h4>Phase 3: Compile and Callbacks</h4>"""

#Compiling Model
model.compile(
    optimizer=tf.keras.optimizers.Adam(learning_rate=0.0005),
    loss="sparse_categorical_crossentropy",
    metrics=["accuracy"]
)

#Adding model checkpoints
from tensorflow.keras.callbacks import ModelCheckpoint

checkpoint = ModelCheckpoint(
    "best_potato_model.keras",
    monitor="val_accuracy",
    save_best_only=True,
    verbose=1
)

#Adding EarlyStopping
from tensorflow.keras.callbacks import EarlyStopping

early_stop = EarlyStopping(
    monitor="val_loss",
    patience=5,
    restore_best_weights=True
)



"""#<h4>Phase 4: Model Training</h4>"""

#Model Training
#EPOCHS = 20 #For MobileNetV2
EPOCHS = 15 #For EfficientNetB0

history = model.fit(
    train_ds,
    validation_data=val_ds,
    epochs=EPOCHS,
    callbacks=[checkpoint, early_stop]
)

#Validation Accuracy
val_loss, val_acc = model.evaluate(val_ds)
print("Validation Accuracy:", val_acc)

"""# <h4>Phase 5: Finalization and Exporting</h4>"""

#Loading the best weights
restore_best_weights=True

#Generating classes
import json
with open("potato_classes.json","w") as f:
  json.dump(class_names, f)
print("Potato Diseases Classes:", class_names)

