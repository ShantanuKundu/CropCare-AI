# ── Standard library imports ──────────────────────────────────────────────
import warnings
warnings.filterwarnings('ignore')

# ── Third-party imports ───────────────────────────────────────────────────
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns

# ── Sklearn – preprocessing & model selection ─────────────────────────────
from sklearn.preprocessing import LabelEncoder
from sklearn.model_selection import train_test_split, GridSearchCV
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, classification_report, confusion_matrix

# ── Persistence ───────────────────────────────────────────────────────────
import pickle

# Load dataset
data = pd.read_csv('Fertilizer Prediction.csv')

# Rename columns for consistency (remove trailing spaces, use underscores)
data.rename(columns={
    'Humidity ':        'Humidity',
    'Soil Type':       'Soil_Type',
    'Crop Type':       'Crop_Type',
    'Fertilizer Name': 'Fertilizer',
}, inplace=True)

# Shape and dtypes
data.info()

# Count of unique values per column
print("\nUnique values per column:")
print(data.nunique())

# Check for missing values
print("\nMissing values:")
print(data.isna().sum())

# Descriptive statistics (numeric + categorical)
data.describe(include='all')

"""
Helper functions for EDA visualisations.
  plot_conti(col) – histogram, boxplot, and boxplot vs target for a numeric column.
  plot_cato(col)  – count plot and count-by-target for a categorical column.
"""

def plot_conti(col):
    fig, axes = plt.subplots(1, 3, figsize=(15, 5), tight_layout=True)
    axes[0].set_title(f'Distribution – {col.name}')
    sns.histplot(col, ax=axes[0])

    axes[1].set_title(f'Outlier check – {col.name}')
    sns.boxplot(col, ax=axes[1])

    axes[2].set_title(f'{col.name} vs Fertilizer')
    sns.boxplot(y=col, x=data.Fertilizer, ax=axes[2])
    plt.show()


def plot_cato(col):
    fig, axes = plt.subplots(1, 2, figsize=(15, 5), tight_layout=True)
    axes[0].set_title(f'Count – {col.name}')
    sns.countplot(col, ax=axes[0])

    axes[1].set_title(f'{col.name} vs Fertilizer')
    sns.countplot(x=col, hue=data.Fertilizer, ax=axes[1])
    plt.show()

# Continuous variables: Temperature, Humidity, Moisture, Nitrogen, Potassium, Phosphorous
for col in ['Temparature', 'Humidity', 'Moisture',
             'Nitrogen',    'Potassium',  'Phosphorous']:
    plot_conti(data[col])

# Categorical variables: Soil_Type, Crop_Type
for col in ['Soil_Type', 'Crop_Type']:
    plot_cato(data[col])

# Cross-variable relationships
fig, axes = plt.subplots(1, 2, figsize=(15, 6), tight_layout=True)
sns.boxplot(x=data.Soil_Type, y=data.Temparature, ax=axes[0]).set_title('Soil type vs Temperature')
sns.boxplot(x=data.Crop_Type, y=data.Humidity,    ax=axes[1]).set_title('Crop type vs Humidity')
plt.show()

# ── Label-encode the three categorical columns ────────────────────────────
encode_soil  = LabelEncoder()
encode_crop  = LabelEncoder()
encode_ferti = LabelEncoder()

data['Soil_Type']  = encode_soil.fit_transform(data['Soil_Type'])
data['Crop_Type']  = encode_crop.fit_transform(data['Crop_Type'])
data['Fertilizer'] = encode_ferti.fit_transform(data['Fertilizer'])

# Helper: display the encoding mapping for any encoder
def encoding_map(encoder, name=''):
    return pd.DataFrame({
        'Original': encoder.classes_,
        'Encoded':  encoder.transform(encoder.classes_),
    }).set_index('Original').rename_axis(name)

print(encoding_map(encode_soil,  'Soil_Type'))
print(encoding_map(encode_crop,  'Crop_Type'))
print(encoding_map(encode_ferti, 'Fertilizer'))

X = data.drop('Fertilizer', axis=1)
y = data['Fertilizer']

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, random_state=1
)

print(f"Train: {X_train.shape}  |  Test: {X_test.shape}")

# ── Baseline Random Forest ────────────────────────────────────────────────
rf_base = RandomForestClassifier(random_state=42)
rf_base.fit(X_train, y_train)

y_pred_base = rf_base.predict(X_test)
print("Baseline accuracy:", accuracy_score(y_test, y_pred_base))
print(classification_report(y_test, y_pred_base))

# ── Coarse grid search ────────────────────────────────────────────────────
param_grid_coarse = {
    'n_estimators':    [300, 400, 500],
    'max_depth':       [5,   10,  15],
    'min_samples_split': [2, 5,   8],
}

grid_coarse = GridSearchCV(
    RandomForestClassifier(random_state=42),
    param_grid_coarse,
    cv=3, verbose=1, n_jobs=-1
)
grid_coarse.fit(X_train, y_train)
print("Best score (coarse):", grid_coarse.best_score_)
print("Best params (coarse):", grid_coarse.best_params_)

# ── Fine grid search around the best coarse params ───────────────────────
param_grid_fine = {
    'n_estimators':    [350, 400, 450],
    'max_depth':       [2, 3, 4, 5, 6, 7],
    'min_samples_split': [2, 5, 8],
}

grid_fine = GridSearchCV(
    RandomForestClassifier(random_state=42),
    param_grid_fine,
    cv=3, verbose=1, n_jobs=-1
)
# Train final model on ALL available data (no hold-out)
grid_fine.fit(X, y)
print("Best score (fine):", grid_fine.best_score_)
print("Best params (fine):", grid_fine.best_params_)

artifacts = {
    'classifier.pkl': grid_fine,
    'fertilizer.pkl': encode_ferti,
}

for path, obj in artifacts.items():
    with open(path, 'wb') as f:
        pickle.dump(obj, f)
    print(f"Saved → {path}")

# ── Verify: load and run a sample prediction ──────────────────────────────
model = pickle.load(open('classifier.pkl', 'rb'))
ferti = pickle.load(open('fertilizer.pkl', 'rb'))
# Sample input: [Temp, Humidity, Moisture, Soil_Type, Crop_Type, N, K, P]
sample = [[34, 67, 62, 0, 1, 7, 0, 30]]
encoded_pred = model.predict(sample)[0]
fertilizer   = ferti.classes_[encoded_pred]

print(f"Predicted fertilizer: {fertilizer}  (encoded label: {encoded_pred})")

